/**
 * Asset URLs from the Jekyll reference build, mapped to logical asset paths.
 * Generated by `scripts/capture-reference.ts`.
 */
export function legacyAssetAliases(): Record<string, string> {
  const file = path.join(ROOT, "src/data/legacy-assets.json");
  return JSON.parse(readFileSync(file, "utf8")) as Record<string, string>;
}

export class RoutingError extends Error {}

/**
 * Builds the redirect rules for Cloudflare's `_redirects` file.
 * A redirect whose source is now a page is omitted, as Netlify did for existing files.
 * A redirect to a missing page is an error.
 */
export function redirects(assets: AssetManifest, exists: (pathname: string) => boolean): Redirect[] {
  const rules: Redirect[] = [];
  for (const [from, to] of PAGE_REDIRECTS) {
    if (exists(from)) continue;
    if (!exists(to)) throw new RoutingError(`Redirect destination ${to} (from ${from}) does not exist`);
    rules.push({ from, to, status: 301 }, { from: `${from}/`, to, status: 301 });
  }
  for (const [from, to] of FILE_REDIRECTS) {
    if (exists(from)) throw new RoutingError(`Redirect source ${from} is a file in the output`);
    if (!exists(to)) throw new RoutingError(`Redirect destination ${to} (from ${from}) does not exist`);
    rules.push({ from, to, status: 301 });
  }
  for (const [legacy, logical] of Object.entries(legacyAssetAliases()).sort(([a], [b]) => (a < b ? -1 : 1))) {
    // The Jekyll pipeline sometimes changed extensions, e.g. `.m4v` to `.mp4`.
    const asset = assets.find(logical) ?? assets.find(logical.replace(/\.[^./]+$/, ""));
    if (!asset) throw new RoutingError(`Legacy asset ${legacy} refers to missing asset "${logical}"`);
    rules.push({ from: legacy, to: assets.build(asset).url, status: 301 });
  }
  // Rules with wildcards come last, which Cloudflare matches more efficiently.
  for (const [from, to] of EXTERNAL_REDIRECTS) rules.push({ from, to, status: 301 });
  return rules;
}

/**
 * Response headers for Cloudflare's `_headers` file.
 *
 * Every path gets the security headers in `SECURITY_HEADERS`
 * and a `Link` header with the site's machine-readable resources in `SITE_LINKS`.
 *
 * The `Link` header doesn't give the Markdown versions of articles.
 * A `/:slug` rule for them would also match every other path with one segment, such as `/feed.xml`,
 * and `_headers` allows only 100 rules, too few for one per article.
 * Later rules could remove the link from the other paths,
 * but the result would depend on the order in which Cloudflare applies rules:
 * the order of the file in `wrangler dev`, but apparently alphabetical by pattern in production.
 *
 * Images, media, scripts, styles, and icons are `Cross-Origin-Resource-Policy: cross-origin` instead of `same-origin`,
 * so that feed readers and other sites can still show them.
 * The Markdown versions of articles aren't indexed by search engines, which index the articles themselves.
 * Cloudflare joins the values of a header that more than one rule sets,
 * so these rules remove the earlier value first with `!`.
 */
export function headers(): string {
  const security = Object.entries(SECURITY_HEADERS).map(([name, value]) => `  ${name}: ${value}`);
  return `/*
${security.join("\n")}
  Link: ${SITE_LINKS}

/assets/*
  Cache-Control: public, max-age=31536000, immutable
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin

/*.ico
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin

/*.png
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin

/*.svg
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin

/feed.xml
  Content-Type: application/atom+xml; charset=utf-8

/*.md
  Content-Type: text/markdown; charset=utf-8
  X-Robots-Tag: noindex

/site.webmanifest
  Content-Type: application/manifest+json; charset=utf-8
`;
}
